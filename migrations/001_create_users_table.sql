-- Create users table for multi-platform user management
CREATE TABLE IF NOT EXISTS `users` (
    `id` BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    `uuid` VARCHAR(36) NOT NULL UNIQUE,
    `telegram_id` BIGINT UNSIGNED NULL,
    `whatsapp_phone` VARCHAR(20) NULL,
    `email` VARCHAR(255) NULL UNIQUE,
    `username` VARCHAR(100) NULL,
    `first_name` VARCHAR(100) NULL,
    `last_name` VARCHAR(100) NULL,
    `phone` VARCHAR(20) NULL,
    `password_hash` VARCHAR(255) NULL,
    `role` ENUM('user', 'premium', 'admin', 'super_admin') NOT NULL DEFAULT 'user',
    `status` ENUM('active', 'inactive', 'banned', 'pending') NOT NULL DEFAULT 'active',
    `language` VARCHAR(10) NOT NULL DEFAULT 'en',
    `timezone` VARCHAR(50) NOT NULL DEFAULT 'UTC',
    `preferences` JSON NULL,
    `last_login_at` TIMESTAMP NULL,
    `last_activity_at` TIMESTAMP NULL,
    `email_verified_at` TIMESTAMP NULL,
    `phone_verified_at` TIMESTAMP NULL,
    `premium_expires_at` TIMESTAMP NULL,
    `api_token` VARCHAR(64) NULL UNIQUE,
    `api_token_expires_at` TIMESTAMP NULL,
    `rate_limit_tier` ENUM('free', 'basic', 'premium', 'enterprise') NOT NULL DEFAULT 'free',
    `daily_imei_limit` INT UNSIGNED NOT NULL DEFAULT 10,
    `daily_download_limit` INT UNSIGNED NOT NULL DEFAULT 5,
    `total_imei_generated` INT UNSIGNED NOT NULL DEFAULT 0,
    `total_files_downloaded` INT UNSIGNED NOT NULL DEFAULT 0,
    `storage_quota_mb` INT UNSIGNED NOT NULL DEFAULT 100,
    `storage_used_mb` INT UNSIGNED NOT NULL DEFAULT 0,
    `referral_code` VARCHAR(20) NULL UNIQUE,
    `referred_by` VARCHAR(20) NULL,
    `referral_count` INT UNSIGNED NOT NULL DEFAULT 0,
    `created_at` TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    `updated_at` TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    `deleted_at` TIMESTAMP NULL,
    
    INDEX `idx_users_telegram_id` (`telegram_id`),
    INDEX `idx_users_whatsapp_phone` (`whatsapp_phone`),
    INDEX `idx_users_email` (`email`),
    INDEX `idx_users_username` (`username`),
    INDEX `idx_users_role` (`role`),
    INDEX `idx_users_status` (`status`),
    INDEX `idx_users_last_activity_at` (`last_activity_at`),
    INDEX `idx_users_premium_expires_at` (`premium_expires_at`),
    INDEX `idx_users_api_token` (`api_token`),
    INDEX `idx_users_referral_code` (`referral_code`),
    INDEX `idx_users_created_at` (`created_at`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
