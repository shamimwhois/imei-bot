-- Create files table for file management
CREATE TABLE IF NOT EXISTS `files` (
    `id` BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    `uuid` VARCHAR(36) NOT NULL UNIQUE,
    `brand_id` BIGINT UNSIGNED NULL,
    `model_id` BIGINT UNSIGNED NULL,
    `category` ENUM('firmware', 'engrom', 'qcnnvram', 'solution', 'manual', 'tool', 'other') NOT NULL,
    `subcategory` VARCHAR(50) NULL,
    `name` VARCHAR(255) NOT NULL,
    `slug` VARCHAR(255) NOT NULL,
    `display_name` VARCHAR(255) NOT NULL,
    `description` TEXT NULL,
    `version` VARCHAR(50) NULL,
    `build_number` VARCHAR(50) NULL,
    `android_version` VARCHAR(20) NULL,
    `security_patch` DATE NULL,
    `region` VARCHAR(50) NULL,
    'carrier` VARCHAR(100) NULL,
    `network_lock` ENUM('unlocked', 'locked', 'carrier_specific', 'region_locked') NOT NULL DEFAULT 'unlocked',
    `file_type` ENUM('zip', '7z', 'rar', 'tar', 'gz', 'bin', 'img', 'cert', 'qcn', 'nvram', 'pdf', 'txt', 'exe', 'other') NOT NULL,
    `file_size_bytes` BIGINT UNSIGNED NOT NULL,
    `file_size_mb` DECIMAL(10,2) GENERATED ALWAYS AS (file_size_bytes / 1048576) STORED,
    `file_hash_md5` VARCHAR(32) NULL,
    `file_hash_sha256` VARCHAR(64) NULL,
    `file_path` VARCHAR(500) NOT NULL,
    `file_url` VARCHAR(500) NULL,
    `cdn_url` VARCHAR(500) NULL,
    `download_count` BIGINT UNSIGNED NOT NULL DEFAULT 0,
    `view_count` BIGINT UNSIGNED NOT NULL DEFAULT 0,
    `rating` DECIMAL(3,2) UNSIGNED NULL,
    `rating_count` INT UNSIGNED NOT NULL DEFAULT 0,
    `is_featured` BOOLEAN NOT NULL DEFAULT FALSE,
    `is_premium` BOOLEAN NOT NULL DEFAULT FALSE,
    `is_verified` BOOLEAN NOT NULL DEFAULT FALSE,
    `is_active` BOOLEAN NOT NULL DEFAULT TRUE,
    `is_virus_scanned` BOOLEAN NOT NULL DEFAULT FALSE,
    `virus_scan_result` JSON NULL,
    `upload_source` ENUM('admin', 'user', 'api', 'import') NOT NULL DEFAULT 'admin',
    `uploaded_by` BIGINT UNSIGNED NULL,
    `approved_by` BIGINT UNSIGNED NULL,
    `approved_at` TIMESTAMP NULL,
    `published_at` TIMESTAMP NULL,
    `expires_at` TIMESTAMP NULL,
    `access_level` ENUM('public', 'registered', 'premium', 'admin') NOT NULL DEFAULT 'public',
    `download_limit` INT UNSIGNED NULL,
    `download_limit_period` ENUM('once', 'daily', 'weekly', 'monthly') NULL,
    `tags` JSON NULL,
    `compatibility` JSON NULL, -- Compatible models, versions, etc.
    'requirements` JSON NULL, -- System requirements
    'changelog` TEXT NULL,
    'installation_notes` TEXT NULL,
    `meta_title` VARCHAR(255) NULL,
    `meta_description` TEXT NULL,
    `meta_keywords` VARCHAR(255) NULL,
    `created_at` TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    `updated_at` TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    `deleted_at` TIMESTAMP NULL,
    
    FOREIGN KEY (`brand_id`) REFERENCES `brands`(`id`) ON DELETE SET NULL ON UPDATE CASCADE,
    FOREIGN KEY (`model_id`) REFERENCES `models`(`id`) ON DELETE SET NULL ON UPDATE CASCADE,
    FOREIGN KEY (`uploaded_by`) REFERENCES `users`(`id`) ON DELETE SET NULL ON UPDATE CASCADE,
    FOREIGN KEY (`approved_by`) REFERENCES `users`(`id`) ON DELETE SET NULL ON UPDATE CASCADE,
    
    INDEX `idx_files_brand_id` (`brand_id`),
    INDEX `idx_files_model_id` (`model_id`),
    INDEX `idx_files_category` (`category`),
    INDEX `idx_files_subcategory` (`subcategory`),
    INDEX `idx_files_name` (`name`),
    INDEX `idx_files_slug` (`slug`),
    INDEX `idx_files_version` (`version`),
    INDEX `idx_files_android_version` (`android_version`),
    INDEX `idx_files_region` (`region`),
    INDEX `idx_files_carrier` (`carrier`),
    INDEX `idx_files_network_lock` (`network_lock`),
    INDEX `idx_files_file_type` (`file_type`),
    INDEX `idx_files_file_size_mb` (`file_size_mb`),
    INDEX `idx_files_is_featured` (`is_featured`),
    INDEX `idx_files_is_premium` (`is_premium`),
    INDEX `idx_files_is_verified` (`is_verified`),
    INDEX `idx_files_is_active` (`is_active`),
    INDEX `idx_files_download_count` (`download_count`),
    INDEX `idx_files_rating` (`rating`),
    INDEX `idx_files_published_at` (`published_at`),
    INDEX `idx_files_created_at` (`created_at`),
    INDEX `idx_files_access_level` (`access_level`),
    
    FULLTEXT KEY `ft_files_search` (`name`, `description`, `tags`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
