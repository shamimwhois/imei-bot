-- Create notifications table for user notifications and alerts
CREATE TABLE IF NOT EXISTS `notifications` (
    `id` BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    `uuid` VARCHAR(36) NOT NULL UNIQUE,
    `user_id` BIGINT UNSIGNED NOT NULL,
    `type` ENUM('info', 'success', 'warning', 'error', 'system', 'marketing', 'security', 'billing', 'feature', 'update') NOT NULL,
    `title` VARCHAR(255) NOT NULL,
    `message` TEXT NOT NULL,
    `data` JSON NULL, -- Additional notification data
    `platform` ENUM('telegram', 'whatsapp', 'web', 'email', 'sms', 'push', 'all') NOT NULL DEFAULT 'all',
    `channel` ENUM('telegram', 'whatsapp', 'web', 'email', 'sms', 'push', 'in_app') NOT NULL,
    `priority` ENUM('low', 'normal', 'high', 'urgent') NOT NULL DEFAULT 'normal',
    `is_read` BOOLEAN NOT NULL DEFAULT FALSE,
    `is_sent` BOOLEAN NOT NULL DEFAULT FALSE,
    `is_delivered` BOOLEAN NOT NULL DEFAULT FALSE,
    `is_failed` BOOLEAN NOT NULL DEFAULT FALSE,
    `sent_at` TIMESTAMP NULL,
    `delivered_at` TIMESTAMP NULL,
    `read_at` TIMESTAMP NULL,
    `expires_at` TIMESTAMP NULL,
    `action_url` VARCHAR(500) NULL,
    `action_text` VARCHAR(100) NULL,
    `dismissible` BOOLEAN NOT NULL DEFAULT TRUE,
    `auto_dismiss` BOOLEAN NOT NULL DEFAULT FALSE,
    `dismiss_after_seconds` INT UNSIGNED NULL,
    `template` VARCHAR(100) NULL,
    `metadata` JSON NULL,
    `retry_count` INT UNSIGNED NOT NULL DEFAULT 0,
    `max_retries` INT UNSIGNED NOT NULL DEFAULT 3,
    `next_retry_at` TIMESTAMP NULL,
    `error_message` TEXT NULL,
    `created_at` TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    `updated_at` TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    
    FOREIGN KEY (`user_id`) REFERENCES `users`(`id`) ON DELETE CASCADE ON UPDATE CASCADE,
    
    INDEX `idx_notifications_user_id` (`user_id`),
    INDEX `idx_notifications_type` (`type`),
    INDEX `idx_notifications_platform` (`platform`),
    INDEX `idx_notifications_channel` (`channel`),
    INDEX `idx_notifications_priority` (`priority`),
    INDEX `idx_notifications_is_read` (`is_read`),
    INDEX `idx_notifications_is_sent` (`is_sent`),
    INDEX `idx_notifications_is_delivered` (`is_delivered`),
    INDEX `idx_notifications_is_failed` (`is_failed`),
    INDEX `idx_notifications_sent_at` (`sent_at`),
    INDEX `idx_notifications_delivered_at` (`delivered_at`),
    INDEX `idx_notifications_read_at` (`read_at`),
    INDEX `idx_notifications_expires_at` (`expires_at`),
    INDEX `idx_notifications_created_at` (`created_at`),
    INDEX `idx_notifications_next_retry_at` (`next_retry_at`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
