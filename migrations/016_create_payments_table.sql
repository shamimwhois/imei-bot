-- Create payments table for comprehensive payment system
CREATE TABLE IF NOT EXISTS `payments` (
    `id` BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    `uuid` VARCHAR(36) NOT NULL UNIQUE,
    `user_id` BIGINT UNSIGNED NOT NULL,
    `transaction_id` VARCHAR(100) NOT NULL UNIQUE,
    `gateway` ENUM('binance_p2p', 'binance_b2b', 'bkash', 'nagad', 'bank_card', 'paypal', 'stripe') NOT NULL,
    `gateway_transaction_id` VARCHAR(255) NULL,
    `amount` DECIMAL(10,2) NOT NULL,
    `currency` VARCHAR(3) NOT NULL DEFAULT 'USD',
    `status` ENUM('pending', 'processing', 'completed', 'failed', 'cancelled', 'refunded', 'disputed') NOT NULL DEFAULT 'pending',
    `payment_method` VARCHAR(50) NULL,
    `payment_details` JSON NULL,
    `webhook_data` JSON NULL,
    `failure_reason` TEXT NULL,
    `refund_id` VARCHAR(100) NULL,
    `refund_amount` DECIMAL(10,2) NULL,
    `refund_reason` TEXT NULL,
    `ip_address` VARCHAR(45) NULL,
    `user_agent` TEXT NULL,
    `device_fingerprint` VARCHAR(255) NULL,
    `processed_at` TIMESTAMP NULL,
    `completed_at` TIMESTAMP NULL,
    `failed_at` TIMESTAMP NULL,
    `refunded_at` TIMESTAMP NULL,
    `expires_at` TIMESTAMP NULL,
    `metadata` JSON NULL,
    `created_at` TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    `updated_at` TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    
    FOREIGN KEY (`user_id`) REFERENCES `users`(`id`) ON DELETE CASCADE ON UPDATE CASCADE,
    
    INDEX `idx_payments_user_id` (`user_id`),
    INDEX `idx_payments_gateway` (`gateway`),
    INDEX `idx_payments_status` (`status`),
    INDEX `idx_payments_transaction_id` (`transaction_id`),
    INDEX `idx_payments_gateway_transaction_id` (`gateway_transaction_id`),
    INDEX `idx_payments_amount` (`amount`),
    INDEX `idx_payments_created_at` (`created_at`),
    INDEX `idx_payments_completed_at` (`completed_at`),
    INDEX `idx_payments_expires_at` (`expires_at`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
